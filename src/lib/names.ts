/**
 * 表の中で会社名を短く出す（事業の種類・カテゴリのページで共通）。
 * かっこの中の補足（旧社名・親会社など）を外し、「／」で並んだ共同の会社や「→」の前後の会社はそれぞれ残したまま「株式会社」を外す。
 * 例：「住友ファーマ株式会社（旧 大日本住友製薬）／Save Medical株式会社」→「住友ファーマ／Save Medical」
 */
export const shortCompany = (n: string) =>
  n
    .replace(/（[^（）]*）/g, '')
    .replace(/（[^（）]*）/g, '')
    .replace(/（.*$/, '')
    .split(/\s*(／|→)\s*/)
    .map((x) => (x === '／' || x === '→' ? x : x.replace(/^\s*株式会社\s*|\s*株式会社\s*$/g, '').trim()))
    .join('')
    .replace(/→/g, ' → ');

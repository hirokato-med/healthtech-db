export function judgeNews(title, companyId) {
  const t = (title ?? '').normalize('NFKC');
  if (VET.test(t) && !/人の|ヒト/.test(t)) return { tier: 'out', reason: '動物医療・ペットの話題で、人のヘルスケア事業の変化ではない', tierBy: 'rule' };
  if (!HC.test(t) && (!companyId || NONHC.test(t))) return { tier: 'out', reason: 'タイトルからはヘルスケアの事業・製品・制度との直接の関係が読み取れない', tierBy: 'rule' };
  if (EVENT.test(t) && !PROMO.test(t) && (companyId || STRONG.test(t))) return { tier: 'top', reason: 'タイトルから、承認・保険適用・事業の開始や終了・資本の動きなど事業上の変化が読み取れる（自動判定）', tierBy: 'rule' };
  return { tier: 'list', reason: 'ヘルスケアと関係はあるが、タイトルからは事業上の大きな変化が読み取れない（自動判定）', tierBy: 'rule' };
}
